// Real Nextcloud browser operations; creates a uniquely named trial card.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const readline=require('node:readline');
const output=process.env.COGNOS_TRIAL_EVIDENCE_DIR || path.join(__dirname,'evidence');
fs.mkdirSync(output,{recursive:true});
const state=JSON.parse(fs.readFileSync(path.join(__dirname,'.secrets/task-journey.json'),'utf8'));
const boardUrl='http://127.0.0.1:8780/index.php/apps/deck/board/'+state.board;
const name='UI task '+Date.now();
const report={scope:'live Nextcloud, Alice UI creation/assignment and Bob mobile completion',checks:[],full_journey:'unverified',service_restart:'unverified',error_recovery:'unverified'};
const child=spawn(process.execPath,[path.join(__dirname,'browser-shell.cjs')],{windowsHide:true,stdio:['pipe','pipe','pipe']});
let waiting,readyResolve;const ready=new Promise(r=>readyResolve=r);
const lines=readline.createInterface({input:child.stdout});
lines.on('line',line=>{if(line==='READY'){readyResolve();return}try{const result=JSON.parse(line);if(waiting){const waiter=waiting;waiting=null;clearTimeout(waiter.timer);result.error?waiter.reject(new Error(result.error)):waiter.resolve(result.result)}}catch{}});
function send(command){return new Promise((resolve,reject)=>{const timer=setTimeout(()=>{waiting=null;reject(new Error('Browser command timed out'))},90000);waiting={resolve,reject,timer};child.stdin.write(JSON.stringify(command)+'\n')})}
const evaluate=evalCode=>send({eval:evalCode});
async function main(){
 await Promise.race([ready,new Promise((_,reject)=>setTimeout(()=>reject(new Error('Browser startup timed out')),20000))]);
 await send({login:'alice'});
 await send({navigate:boardUrl});
 await send({wait:'!!document.querySelector(\'button[aria-label="添加卡片"]\')'});
 await evaluate('document.querySelector(\'button[aria-label="添加卡片"]\').click();true');
 await send({wait:'!!document.querySelector(\'input[placeholder="卡片名"]\')'});
 await evaluate(`(()=>{const e=document.querySelector('input[placeholder="卡片名"]');e.value=${JSON.stringify(name)};e.dispatchEvent(new Event('input',{bubbles:true}));return true})()`);
 await evaluate('document.querySelector(\'input[placeholder="卡片名"]\').closest("form").querySelector("input[type=submit]").click();true');
 const cardFinder=`Array.from(document.querySelectorAll('#app-content-vue h4')).find(e=>e.textContent.trim()===${JSON.stringify(name)})`;
 await send({wait:`!!(${cardFinder})`});
 await evaluate(`${cardFinder}.click();true`);
 await send({wait:'!!document.querySelector(\'input[placeholder="选择要分配给此卡片的用户…"]\')'});
 report.card_url=await evaluate('location.pathname');
 const createRequests=(await send({networkSummary:true})).requests.filter(r=>r.method==='POST'&&r.path==='/ocs/v2.php/apps/cognos/api/v1.0/cards');
 assert.equal(createRequests.length,1);assert.equal(createRequests[0].status,200);
 report.create_endpoint=createRequests[0].path;
 report.checks.push('Alice creates a new task through the visible form');
 await evaluate('(()=>{const e=document.querySelector(\'input[placeholder="选择要分配给此卡片的用户…"]\');e.focus();e.value="B";e.dispatchEvent(new Event("input",{bubbles:true}));return true})()');
 await send({wait:'Array.from(document.querySelectorAll("[role=option]")).some(e=>e.innerText.includes("试用同学 B"))'});
 await evaluate('Array.from(document.querySelectorAll("[role=option]")).find(e=>e.innerText.includes("试用同学 B")).click();true');
 await send({wait:'Array.from(document.querySelectorAll(".vs__selected")).some(e=>e.innerText.includes("试用同学 B"))'});
 report.checks.push('Alice selects Bob as assignee through the member selector');
 await send({screenshot:'UI验收-A指派'});
 await send({logout:true});await send({login:'bob'});
 await send({navigate:'http://127.0.0.1:8780/index.php/apps/deck/upcoming'});
 await send({wait:`!!(${cardFinder})`});
 await evaluate(`${cardFinder}.scrollIntoView({inline:'center',block:'center'});true`);
 assert.equal(await evaluate(`(()=>{const e=${cardFinder};const r=e.getBoundingClientRect();return r.right>0&&r.left<innerWidth&&r.bottom>0&&r.top<innerHeight})()`),true);
 report.checks.push('Bob discovers the assigned task in upcoming cards and scrolls it into view');
 await send({screenshot:'UI验收-B个人任务'});
 await send({viewport:390});await evaluate(`${cardFinder}.click();true`);
 await send({wait:'Array.from(document.querySelectorAll("button")).some(e=>e.innerText.trim()==="标记为已完成")'});
 await evaluate('Array.from(document.querySelectorAll("button")).find(e=>e.innerText.trim()==="标记为已完成").click();true');
 await evaluate('Array.from(document.querySelectorAll("button,[role=tab]")).find(e=>e.innerText.trim()==="活动").click();true');
 await send({wait:'document.body.innerText.includes("指派给了") && document.body.innerText.includes("标记为已完成")'});
 report.checks.push('Bob completes the task at 390px and sees create/assignment/completion history');
 await send({screenshot:'UI验收-手机完成历史'});
 await send({viewport:1280});
 await send({navigate:'http://127.0.0.1:8780/index.php/apps/deck/upcoming'});
 await send({wait:'document.querySelector("#app-content-vue")?.innerText.includes("创建您的第一张卡片")'});
 assert.equal(await evaluate(`document.querySelector('#app-content-vue .overview').innerText.includes(${JSON.stringify(name)})`),false);
 const createdId=Number(report.card_url.match(/card\/(\d+)/)[1]);
 await send({wait:`document.querySelector('[data-cognos-personal-card="${createdId}"] [data-cognos-personal-status]')?.dataset.cognosPersonalStatus === 'done'`});
 report.checks.push('Completed task leaves native upcoming cards and remains discoverable in personal tasks');
 await send({navigate:'http://127.0.0.1:8780'+report.card_url});
 await send({wait:'Array.from(document.querySelectorAll("button,[role=tab]")).some(e=>e.innerText.trim()==="活动")'});
 await evaluate('Array.from(document.querySelectorAll("button,[role=tab]")).find(e=>e.innerText.trim()==="活动").click();true');
 await send({wait:'document.body.innerText.includes("指派给了") && document.body.innerText.includes("标记为已完成")'});
 report.checks.push('History survives a fresh page navigation');
 report.result='passed';
}
main().catch(async e=>{report.result='failed';report.failure=e.message;report.network=await send({networkSummary:true});report.visible_error=await evaluate('document.querySelector("[data-cognos-task-feedback]")?.innerText');process.exitCode=1}).finally(async()=>{fs.writeFileSync(path.join(output,'任务浏览器-自动验收.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));child.stdin.write('{"close":true}\n');setTimeout(()=>child.kill(),2000).unref();});
